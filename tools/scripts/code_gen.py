def crc16_ccitt(data, crc=0xFFFF):
    """
    Calculate the CRC16-CCITT checksum for the given data.

    Args:
        data (bytes): Data to calculate the checksum for.
        crc (int): Initial CRC value.

    Returns:
        int: CRC16-CCITT checksum.
    """
    for byte in data:
        crc ^= byte << 8
        for _ in range(8):
            if crc & 0x8000:
                crc = ((crc << 1) ^ 0x1021) & 0xFFFF
            else:
                crc = (crc << 1) & 0xFFFF
    return crc

